    <section class="imm-new imm-section" aria-labelledby="imm-new-title">
        <div class="imm-wrap imm-new-grid">
            <div>
                <p class="imm-eyebrow">A different approach</p>
                <h2 id="imm-new-title">New Paradigm – Immunotherapy and Vaccines</h2>
            </div>
            <div class="imm-copy">
                <p>Conversely, immunotherapy is like using a sniper rifle to shoot and kill only the cancer cells.</p>
                <p>In recent years, advances in science and biotechnology have proven that the body’s own immune system is quite effective at targeting and killing abnormal cells, germs and viruses, and has been doing it since the beginning of time. The main problem is that cancer grows at a much faster rate than the body’s normal immune response rate.</p>
                <p>Much like vaccines that train the body to recognize and destroy other diseases, cancer vaccines can train the body to target and destroy specific cancer cells. Cancer vaccines are also known as vaccine therapy or immunotherapy. They are different from vaccines that prevent disease, as they are designed to fight cancer that already exists in the body.</p>
            </div>
        </div>
    </section>

    <section class="imm-section" id="imm-types" aria-labelledby="imm-types-title">
        <div class="imm-wrap">
            <div class="imm-section-heading">
                <div><p class="imm-eyebrow">Therapy overview</p><h2 id="imm-types-title">Types of Immunotherapy</h2></div>
                <p>According to the National Cancer Institute, there are several types of immunotherapies.</p>
            </div>
            <article class="imm-therapy" aria-labelledby="imm-checkpoint-title">
                <span class="imm-number" aria-hidden="true">01</span>
                <div class="imm-copy">
                    <h3 id="imm-checkpoint-title">Immune Checkpoint Inhibitors</h3>
                    <p>These are drugs that block immune checkpoints. Checkpoints are a normal part of the immune system and keep immune responses from being too strong. By blocking them, these drugs allow immune cells to respond more strongly to cancer.</p>
                    <p>Example blockbuster immunotherapy drugs:</p>
                    <ul><li>Keytruda (Merck)</li><li>Opdivo (Bristol Myers Squibb)</li></ul>
                </div>
                <figure><img src="./assets/images/immtype1.png" alt="Illustration accompanying immune checkpoint inhibitors" width="1921" height="1921"></figure>
            </article>
            <article class="imm-therapy" aria-labelledby="imm-cart-title">
                <span class="imm-number" aria-hidden="true">02</span>
                <div class="imm-copy">
                    <h3 id="imm-cart-title">T-cell Transfer Therapy (CAR-T)</h3>
                    <p>This is a personalized treatment that boosts the natural ability of the body’s immune T-cells to fight cancer. In this treatment, immune cells are taken from the tumor. Those that are most active against the cancer are selected or genetically modified in the lab to better attack your cancer cells, grown in large batches, and put back into the body through an injection.</p>
                </div>
                <figure><img src="./assets/images/immtype2.png" alt="Illustration accompanying T-cell transfer therapy" width="1921" height="1921"></figure>
            </article>
            <article class="imm-therapy" aria-labelledby="imm-antibodies-title">
                <span class="imm-number" aria-hidden="true">03</span>
                <div class="imm-copy">
                    <h3 id="imm-antibodies-title">Monoclonal Antibodies</h3>
                    <p>These are immune system proteins created in the lab that are designed to bind to specific targets on cancer cells. Some monoclonal antibodies mark cancer cells so that they will be better seen and destroyed by the immune system. Such monoclonal antibodies are a type of immunotherapy.</p>
                    <p>As a point of reference, the Pfizer and Modern COVID-19 vaccines are monoclonal antibodies for the coronavirus.</p>
                </div>
                <figure><img src="./assets/images/immtype3.png" alt="Illustration accompanying monoclonal antibodies" width="1921" height="1921"></figure>
            </article>
            <article class="imm-therapy" aria-labelledby="imm-vaccines-title">
                <span class="imm-number" aria-hidden="true">04</span>
                <div class="imm-copy">
                    <h3 id="imm-vaccines-title">Treatment Vaccines</h3>
                    <p>These work against cancer by boosting the immune system’s response to cancer cells. Treatment vaccines are different from the ones that help prevent diseases.</p>
                </div>
                <figure><img src="./assets/images/immtype5.jpg" alt="Image accompanying treatment vaccines" width="467" height="450"></figure>
            </article>
            <article class="imm-therapy" aria-labelledby="imm-modulators-title">
                <span class="imm-number" aria-hidden="true">05</span>
                <div class="imm-copy">
                    <h3 id="imm-modulators-title">Immune System Modulators</h3>
                    <p>These enhance the body’s immune response against cancer. Some of these agents affect specific parts of the immune system, whereas others affect the immune system in a more general way.</p>
                </div>
                <figure><img src="./assets/images/immtype4.jpg" alt="Image accompanying immune system modulators" width="467" height="450"></figure>
            </article>
        </div>
