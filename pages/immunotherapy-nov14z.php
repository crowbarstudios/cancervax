        <div class="imm-wrap imm-paradigm">
            <div class="imm-copy">
                <p class="imm-eyebrow">Treatment approaches</p>
                <h2 id="imm-old-title">Old Paradigm – Chemotherapy and Radiation</h2>
                <p>For decades, surgery, chemotherapy, and radiation therapy have been the standards of care for cancer treatment and are often the only options. They operate on the basic premise that cancer cells are fast-growing cells, so using powerful toxic chemicals (chemotherapy) or powerful X-rays (radiation), they hope to kill those cells to stop the cancer. The problem is that these treatments are not always very targeted, so they also kill normal fast-growing cells, such as hair cells, intestine cells, mouth-lining cells, and others. This inadvertent side effect of killing healthy cells is what causes the debilitating side effects of chemotherapy and radiation and a reduced quality of life for cancer patients.</p>
                <p>Using “chemo” has been likened to throwing a grenade into the body with the hope that it will kill the cancer and not the body.</p>
            </div>
